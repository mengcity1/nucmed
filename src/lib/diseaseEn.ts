/** 单个病名 → 英文（未收录则原样返回，避免丢信息） */
export function diseaseEn(zh: string): string {
  return DISEASE_EN[zh.trim()] ?? zh;
}

/** 多病名（顿号/逗号分隔）→ 英文串，用于表格单元格 */
export function enDiseases(raw: string | null | undefined): string {
  if (!raw) return "";
  return raw
    .split(/[、,;；/]/)
    .map((s) => s.trim())
    .filter(Boolean)
    .map(diseaseEn)
    .join(", ");
}

/** 英文名是否已收录（搜索时用来判断要不要同时匹配英文） */
export function hasDiseaseEn(zh: string): boolean {
  return Object.prototype.hasOwnProperty.call(DISEASE_EN, zh.trim());
}

